import java.util.List;

// BackendPy：Module -> Python 源码
// 直接翻译栈式字节码：操作数栈用 list 实现，局部变量按调用帧保存，
// 每条字节码对应一个同名运行时函数（PUSH / STORE / IADD ...）。
public class BackendPy {

    public static String emit(Module m) {
        StringBuilder sb = new StringBuilder();
        sb.append("#!/usr/bin/env python3\n");
        sb.append("# Generated by UniVM BackendPy\n");
        sb.append("# 栈式字节码 -> Python：list 作为操作数栈，dict 作为调用帧。\n\n");
        if (m.hasAnySysCall()) {
            sb.append("import time\n");
            sb.append("import os\n\n");
        }
        sb.append(RUNTIME);

        // 函数体：参数由 CALL 写入新帧，函数本身不接收 Python 参数
        for (Function fn : m.funcs.values()) {
            sb.append("def _fn_").append(fn.name).append("():\n");
            Emitter e = new Emitter(sb, m);
            e.block(fn.body, "    ");
            if (fn.body.isEmpty()) sb.append("    pass\n");
            sb.append("\n\n");
        }

        // 函数表：名称 -> (函数体, 参数名列表)
        sb.append("FUNCS.update({\n");
        for (Function fn : m.funcs.values()) {
            sb.append("    ").append(pyString(fn.name)).append(": (_fn_").append(fn.name).append(", [");
            for (int k = 0; k < fn.params.size(); k++) {
                if (k > 0) sb.append(", ");
                sb.append(pyString(fn.params.get(k)));
            }
            sb.append("]),\n");
        }
        sb.append("})\n\n");

        // main 也编译为函数，RET 可正常抛出 _Return
        sb.append("def _main():\n");
        Emitter mainE = new Emitter(sb, m);
        mainE.block(m.main, "    ");
        if (m.main.isEmpty()) sb.append("    pass\n");
        sb.append("\n\nif __name__ == \"__main__\":\n");
        sb.append("    try:\n");
        sb.append("        _main()\n");
        sb.append("    except _Return:\n");
        sb.append("        pass\n");
        return sb.toString();
    }

    private static final String RUNTIME = """
            stack = []
            frames = [{}]
            FUNCS = {}


            class _Return(Exception):
                def __init__(self, value):
                    self.value = value


            def PUSH(value):
                stack.append(value)


            def LOAD(name):
                stack.append(frames[-1].get(name, 0))


            def STORE(name):
                frames[-1][name] = stack.pop()


            def IADD():
                b = stack.pop()
                a = stack.pop()
                stack.append(a + b)


            def ISUB():
                b = stack.pop()
                a = stack.pop()
                stack.append(a - b)


            def IMUL():
                b = stack.pop()
                a = stack.pop()
                stack.append(a * b)


            def IDIV():
                b = stack.pop()
                a = stack.pop()
                q = abs(a) // abs(b)          # Java long 除法向零截断
                stack.append(-q if (a < 0) != (b < 0) else q)


            def INEG():
                stack.append(-stack.pop())


            def IEQ():
                b = stack.pop()
                a = stack.pop()
                stack.append(1 if a == b else 0)


            def INE():
                b = stack.pop()
                a = stack.pop()
                stack.append(1 if a != b else 0)


            def ILT():
                b = stack.pop()
                a = stack.pop()
                stack.append(1 if a < b else 0)


            def IGT():
                b = stack.pop()
                a = stack.pop()
                stack.append(1 if a > b else 0)


            def ILE():
                b = stack.pop()
                a = stack.pop()
                stack.append(1 if a <= b else 0)


            def IGE():
                b = stack.pop()
                a = stack.pop()
                stack.append(1 if a >= b else 0)


            def PRINT_INT():
                print(stack.pop())


            def PRINT_STR():
                print(stack.pop())


            def SLEN():
                stack.append(len(stack.pop()))


            def POP():
                stack.pop()


            def ANEW():
                size = stack.pop()
                stack.append([0] * size)


            def AGET():
                idx = stack.pop()
                arr = stack.pop()
                if idx < 0 or idx >= len(arr):
                    raise IndexError("数组下标越界: %d" % idx)
                stack.append(arr[idx])


            def ASET():
                value = stack.pop()
                idx = stack.pop()
                arr = stack.pop()
                if idx < 0 or idx >= len(arr):
                    raise IndexError("数组下标越界: %d" % idx)
                arr[idx] = value


            def ALEN():
                stack.append(len(stack.pop()))


            def CALL(name, argc):
                args = [stack.pop() for _ in range(argc)][::-1]
                fn, params = FUNCS[name]
                frame = {}
                for param, value in zip(params, args):
                    frame[param] = value
                frames.append(frame)
                try:
                    fn()
                    result = 0
                except _Return as ret:
                    result = ret.value
                finally:
                    frames.pop()
                stack.append(result)


            def RET():
                raise _Return(stack.pop())


            def SYS_CALL(name, argc):
                if name == "time":
                    if argc != 0:
                        raise RuntimeError("time 参数个数错误: %d" % argc)
                    stack.append(int(time.time() * 1000))
                elif name == "readFile":
                    if argc != 1:
                        raise RuntimeError("readFile 参数个数错误: %d" % argc)
                    path = stack.pop()
                    try:
                        with open(path, "rb") as f:
                            stack.append(f.read().decode("utf-8"))
                    except (OSError, UnicodeError):
                        stack.append("")
                elif name == "writeFile":
                    if argc != 2:
                        raise RuntimeError("writeFile 参数个数错误: %d" % argc)
                    content = stack.pop()
                    path = stack.pop()
                    try:
                        with open(path, "wb") as f:
                            f.write(content.encode("utf-8"))
                        stack.append(0)
                    except OSError:
                        stack.append(-1)
                else:
                    raise RuntimeError("未知标准库函数: " + name)


            """;

    private static String pyString(String s) {
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'";
    }

    private static String pyLiteral(String s) {
        StringBuilder b = new StringBuilder("\"");
        for (int k = 0; k < s.length(); k++) {
            char c = s.charAt(k);
            switch (c) {
                case '\\': b.append("\\\\"); break;
                case '"':  b.append("\\\""); break;
                case '\n': b.append("\\n"); break;
                case '\r': b.append("\\r"); break;
                case '\t': b.append("\\t"); break;
                default:
                    if (c < 0x20) b.append(String.format("\\x%02x", (int) c));
                    else b.append(c);
            }
        }
        return b.append('"').toString();
    }

    private static class Emitter {
        private final StringBuilder sb;
        private final Module module;

        Emitter(StringBuilder sb, Module module) {
            this.sb = sb;
            this.module = module;
        }

        void block(List<BytecodeNode> ns, String ind) {
            for (BytecodeNode n : ns) node(n, ind);
        }

        private void line(String ind, String code) {
            sb.append(ind).append(code).append('\n');
        }

        void node(BytecodeNode n, String ind) {
            if (n instanceof Instruction) {
                Instruction i = (Instruction) n;
                switch (i.op) {
                    case PUSH:      line(ind, "PUSH(" + i.operand + ")"); break;
                    case SCONST:    line(ind, "PUSH(" + pyLiteral(module.stringPool.get((int) i.operand)) + ")"); break;
                    case LOAD:      line(ind, "LOAD(" + pyString(i.str) + ")"); break;
                    case STORE:     line(ind, "STORE(" + pyString(i.str) + ")"); break;
                    case IADD:      line(ind, "IADD()"); break;
                    case ISUB:      line(ind, "ISUB()"); break;
                    case IMUL:      line(ind, "IMUL()"); break;
                    case IDIV:      line(ind, "IDIV()"); break;
                    case INEG:      line(ind, "INEG()"); break;
                    case IEQ:       line(ind, "IEQ()"); break;
                    case INE:       line(ind, "INE()"); break;
                    case ILT:       line(ind, "ILT()"); break;
                    case IGT:       line(ind, "IGT()"); break;
                    case ILE:       line(ind, "ILE()"); break;
                    case IGE:       line(ind, "IGE()"); break;
                    case PRINT_INT: line(ind, "PRINT_INT()"); break;
                    case PRINT_STR: line(ind, "PRINT_STR()"); break;
                    case SLEN:      line(ind, "SLEN()"); break;
                    case POP:       line(ind, "POP()"); break;
                    case ANEW:      line(ind, "ANEW()"); break;
                    case AGET:      line(ind, "AGET()"); break;
                    case ASET:      line(ind, "ASET()"); break;
                    case ALEN:      line(ind, "ALEN()"); break;
                    case CALL:      line(ind, "CALL(" + pyString(i.str) + ", " + i.operand + ")"); break;
                    case SYS_CALL:  line(ind, "SYS_CALL(" + pyString(i.str) + ", " + i.operand + ")"); break;
                    case RET:       line(ind, "RET()"); break;
                    default: throw new RuntimeException("BackendPy 不支持的指令: " + i.op);
                }
            } else if (n instanceof IfNode) {
                IfNode f = (IfNode) n;
                block(f.cond, ind);
                sb.append(ind).append("if stack.pop():\n");
                if (f.then.isEmpty()) sb.append(ind).append("    pass\n");
                else block(f.then, ind + "    ");
                sb.append(ind).append("else:\n");
                if (f.els.isEmpty()) sb.append(ind).append("    pass\n");
                else block(f.els, ind + "    ");
            } else if (n instanceof WhileNode) {
                WhileNode w = (WhileNode) n;
                sb.append(ind).append("while True:\n");
                block(w.cond, ind + "    ");
                sb.append(ind).append("    if not stack.pop():\n");
                sb.append(ind).append("        break\n");
                if (w.body.isEmpty()) sb.append(ind).append("    pass\n");
                else block(w.body, ind + "    ");
            }
        }
    }
}
